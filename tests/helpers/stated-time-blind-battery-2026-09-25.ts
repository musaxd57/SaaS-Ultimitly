// Spec syntax: "HH:MM+" = MUST_ACCEPT, "HH:MM-" = MUST_REJECT, trailing "?" = label declared
// DEBATABLE up front (bare-hour +12 readings, activity trips, taxi pickup, time-only replies, ranges...).
// Labelling policy (decided blind):
//  - ACCEPT: the guest states their own departure/checkout time (plan/intent), incl. by/kadar/around,
//    "leave for the airport at X" (by design), conditional intent is debatable.
//  - REJECT: other events (flight, train, breakfast, cleaner, AC, taxi*), check-in/arrival, refusals,
//    questions/requests, replaced times, counters, dates, phone numbers, prices, ages, room numbers,
//    digits inside other times/dates, wrong half of the day when am/pm or a day-period word is given.

export type Label = "MUST_ACCEPT" | "MUST_REJECT";
export interface Cand { t: string; label: Label; debatable: boolean }
export interface Case { id: string; lang: "tr" | "en" | "de" | "fr" | "es"; cat: string; msg: string; prev?: string; cands: Cand[] }

type Row = [cat: string, msg: string, specs: string, prev?: string];

function parse(specs: string): Cand[] {
  return specs.trim().split(/\s+/).map((s) => {
    const m = /^(\d{2}:\d{2})([+-])(\?)?$/.exec(s);
    if (!m) throw new Error("bad spec " + s);
    return { t: m[1], label: m[2] === "+" ? "MUST_ACCEPT" : "MUST_REJECT", debatable: !!m[3] };
  });
}

